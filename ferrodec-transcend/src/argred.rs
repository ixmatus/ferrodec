/// Decimal digit `i` of `2/π` (1-indexed; `i = 1` is the `6` in
/// `0.636…`). Returns `0` for indices beyond the table — callers must
/// pre-clip.
#[inline]
fn two_over_pi_digit(i: usize) -> u8 {
    debug_assert!((1..=table::TWO_OVER_PI_DIGITS).contains(&i));
    let idx = i - 1;
    let limb = table::TWO_OVER_PI[idx / 9];
    // Position 0 in a limb is the MSD (10^8), position 8 is the LSD.
    let pos = idx % 9;
    let shift = 10u32.pow(8 - pos as u32);
    ((limb / shift) % 10) as u8
}

