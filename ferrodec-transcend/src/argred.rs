// Public entry point.

/// Reduce `|x|` for sin/cos. Caller must have already separated the
/// sign of `x`; this function operates on the absolute value.
///
/// Returns `(k mod 4, r, status)` such that
///
/// ```text
/// |x|  =  k · π/2 + r
/// |r| ≤ π/4 (with at most ~2 ULP overrun)
/// ```
///
/// `k` is `round(|x| · 2/π)` (round-half-away-from-zero — ties don't
/// arise in practice since the product is irrational).
///
/// `r` is returned at extended precision so the downstream Taylor
/// series in `sincos.rs` runs without losing the ~38 digits of
/// fractional residual that the windowed multiplication produced.
///
/// `x` must be finite. NaN, Infinity, and Zero are handled by the
/// caller before reaching here.
pub fn reduce<F: DecimalFormat>(x: F) -> (u32, Extended, Status) {
    let cls = x.classify();
    let (biased_exp, c) = match cls {
        Class::Finite {
            biased_exp,
            coefficient,
            ..
        } => (biased_exp, coefficient),
        // Caller filters these out, but be defensive.
        _ => return (0, Extended::from_format(x), Status::OK),
    };
    debug_assert!(c != 0);

    let q = biased_exp as i32 - F::BIAS; // unbiased exponent

    // Magnitude of |x|: |x| = c · 10^q. Decade ≈ q + digits(c) − 1.
    let dig_c = decimal_digit_count(c) as i32;
    let decade = q + dig_c - 1;

    // If |x| < π/4 ≈ 0.785, the reduction is trivially k = 0, r = |x|.
    // π/4 is between 10^{-1} and 1, so the safe shortcut is decade < -1
    // (i.e., |x| < 0.1 — well below π/4).
    if decade < -1 {
        // r = |x| as Extended.
        let mut r = Extended::from_format(x);
        r.sign = false;
        return (0, r, Status::INEXACT);
    }

    // Compute the window [i_lo, i_hi] of `2/π` digits we need.
    //
    // Mathematically i_lo = q − 1 (so the window's MSD is the digit
    // that lands at the 10^1 place of `c · 2/π`). Clipped to ≥ 1.
    // i_hi = q + I_HI_OFFSET. Clipped to ≤ TWO_OVER_PI_DIGITS — but
    // we sized the table so this never trips for a normal Decimal128.
    let i_hi_signed = q + I_HI_OFFSET as i32;
    if i_hi_signed < 1 {
        // Window empty: |x · 2/π| ≪ 10^{-FRAC_DIGITS}, so k = 0.
        let mut r = Extended::from_format(x);
        r.sign = false;
        return (0, r, Status::INEXACT);
    }
    let i_hi = (i_hi_signed as usize).min(table::TWO_OVER_PI_DIGITS);
    let i_lo_signed = q - 1;
    let i_lo = if i_lo_signed < 1 {
        1
    } else {
        i_lo_signed as usize
    };
    debug_assert!(i_lo <= i_hi);

    // W = window value as a U384 (≤ 78 decimal digits ≤ 2^259).
    let w = extract_window(i_lo, i_hi);

    // P = c × W. With FRAC_DIGITS = 76 the window is up to 115
    // digits and `c` is up to 34 digits — the product can reach
    // ~149 digits, exceeding `U384` (~115). The full product lives
    // in `U512` (~154 digits).
    let p = u384_mul_u128_to_u512(w, c);

    // The window value used the digits at positions i_lo..i_hi of 2/π,
    // which in `c · 10^q · 2/π` corresponds to the LSD of P sitting at
    // position 10^{q − i_hi} of x · 2/π. So P · 10^{q − i_hi} = the
    // windowed approximation to x · 2/π.
    //
    // We want round(x · 2/π) mod 4 and the fractional part. The
    // "decimal point" of P is positioned (i_hi − q) digits from the
    // right.
    //
    // For i_hi = q + I_HI_OFFSET (the unclipped case), this is exactly
    // I_HI_OFFSET = 113 (= FRAC_DIGITS + 33 + CARRY_GUARD = 76 + 33 + 4).
    // We rely on that: the table is sized so we never hit the i_hi clip
    // in practice (q_max + I_HI_OFFSET = 6111 + 113 = 6224 ≤ 6300, with
    // 76 digits of head-room before the table runs out). For the i_lo
    // clip (small q), shifting changes the window's interpretation:
    // dropping the digits below i_lo = 1 means we lose the d_0, d_{-1},
    // … positions, which don't exist because 2/π < 1. So the math works
    // out unchanged.
    debug_assert_eq!(
        i_hi - i_lo + 1,
        (i_hi_signed as usize - i_lo_signed.max(1) as usize) + 1
    );
    debug_assert!(i_hi as i32 - q == I_HI_OFFSET as i32);

    let split = split_product(p);

    // Decide whether the fractional part is ≥ 0.5: leading digit ≥ 5.
    let leading_frac = split.frac_digits[0];
    let round_up = leading_frac >= 5;

    let floor_mod_4 = split.floor_mod_100 % 4;
    let k_mod_4 = if round_up {
        (floor_mod_4 + 1) % 4
    } else {
        floor_mod_4
    };

    // Build r at extended precision. The caller passes the ABS value;
    // the residual sign is entirely determined by `round_up`.
    let r = make_residual(split.frac_digits, round_up, false);
    (k_mod_4, r, Status::INEXACT)
}

