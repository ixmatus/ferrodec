#[cfg(test)]
mod tests {
    extern crate alloc;
    use super::*;

    #[test]
    fn first_digits_of_two_over_pi() {
        // 2/π = 0.63661977236758134307553505349005744813783858296183…
        let want = "63661977236758134307553505349005744813";
        for (i, ch) in want.char_indices() {
            let got = two_over_pi_digit(i + 1);
            let want_d = ch.to_digit(10).unwrap() as u8;
            assert_eq!(
                got,
                want_d,
                "digit {} mismatch: got {got}, want {want_d}",
                i + 1
            );
        }
    }

    #[test]
    fn pi_over_two_coef_matches_string() {
        // PI_OVER_TWO_COEF_38 must be the 38 leading decimal digits of
        // table::PI_OVER_TWO_STR (without the decimal point), parsed as
        // a u128.
        let s = table::PI_OVER_TWO_STR
            .chars()
            .filter(char::is_ascii_digit)
            .take(38)
            .collect::<alloc::string::String>();
        let derived: u128 = s.parse().unwrap();
        assert_eq!(derived, PI_OVER_TWO_COEF_38);
    }
}
