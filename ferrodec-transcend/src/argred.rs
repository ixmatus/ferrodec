//! Moved from `ferrodec/src/math/argred.rs` @ commit 82a7fe1 (P0a.2 c7).
//! Behaviour-neutral: genericized over [`DecimalFormat`]; the
//! `Decimal128` instantiation is byte-identical to the pre-move kernel.
//!
//! Payne-Hanek argument reduction for `sin` / `cos`.
//!
//! ## Why
//!
//! The naive reduction `r = x − round(x / (π/2)) · (π/2)` works while
//! `|x|` is small enough that the cancellation in the subtraction
//! leaves at least 34 good digits. For `Decimal128`'s 34-digit
//! envelope that holds up to `|x| ≈ 10^9`; past that, more digits of
//! `π/2` get cancelled out than the native arithmetic carries, and
//! `r` rapidly loses meaning.
//!
//! ## Algorithm
//!
//! Payne and Hanek (1983, [doi:10.1145/1057600.1057602]) observed that the
//! cancellation is itself the reduction — multiplying `x` by an
//! extended-precision `2/π` and discarding the integer part gives the
//! reduced argument *without* any catastrophic subtraction. The product
//! only needs digits of `2/π` in a narrow window around the
//! integer / fraction boundary of `x · 2/π`, so storage scales linearly
//! with the input's exponent rather than exponentially with the loss
//! of precision.
//!
//! For `Decimal128` the maximum magnitude is `≈ 10^{6145}`, so we
//! embed `2/π` to 6 408 decimal digits (≈ 2.9 KB in flash, lives in
//! `.rodata`; sized for the widest reader, the rung 2 window below).
//! Each rung 1 call extracts a ~78-digit window indexed by the input's
//! unbiased exponent, multiplies by the 34-digit coefficient
//! into a `U384`, and reads the integer part `mod 4` and the leading
//! ~38 fractional digits directly out of the result. The fractional
//! part is then multiplied by a 38-digit truncated `π/2` constant
//! (`PI_OVER_TWO_COEF_38`, derived from and pinned against the
//! 120-digit `table::PI_OVER_TWO_STR` reference) to yield `r` with 1-2
//! ULP of error against the true reduction. The 120-digit string is a
//! derivation reference only; the rung 1 reduction reads the 38-digit
//! truncation, whose truncation-error discharge that constant's doc
//! records honestly (fd-aqs.10).
//!
//! `reduce_wide` (ADR-0059 M6) is the rung 2 sibling: a ~182-digit
//! window in `U768`, 143 fractional digits, and a 115-digit truncated
//! `π/2`, delivering the residual into `Extended2` with up to 110
//! surviving digits; its truncation discharge is analytic, not
//! empirical (< 10^-114 relative).
//!
//! `reduce_dyn` (M8b, behind the `unbounded-ladder` feature) is the
//! third sibling: the same pipeline with every width a function of the
//! rung's runtime precision `p`, and both constants computed per call
//! rather than read from storage. The table below cannot serve it — a
//! stored table caps the precision a rung can reach, and the Ziv
//! driver's doubling has no cap — so the `2/π` digits come from
//! `ferrodec_multiword::bigconst::two_over_pi_digits` and the `π/2`
//! coefficient from `bigconst::pi_digits`.
//!
//! ## Storage budget for the table
//!
//! The rung 1 window is `d_{q-1} … d_{q + 113}` and the rung 2 window
//! `d_{q-1} … d_{q + 180}`, where `q` is the unbiased exponent
//! (`biased_exp − BIAS`). With `q_max = +6111` (largest representable
//! unbiased exponent for a normalised coefficient) the deepest read is
//! `d_{6291}`, so 6 408 digits (712 whole base-10^9 limbs) gives 117
//! digits of headroom.
//!
//! ## Sign and rounding
//!
//! [`reduce`] takes an absolute value (sign separated by the caller)
//! and returns `k = round(|x| · 2/π) mod 4` plus the residual `r`,
//! where `|x| − k · π/2 = r` and `|r| ≤ π/4 + 2 · ULP(π/4)`. Callers
//! must adjust `k` and the residual sign for negative inputs (see
//! `sincos.rs`).

