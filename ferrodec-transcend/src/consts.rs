    /// Each rung 2 accessor parses its literal into a coefficient at
    /// most `EXT2_PRECISION + 5` digits (the invariant `parse_str`
    /// debug-asserts) and agrees in value with its rung 1 counterpart
    /// to rung 1 width — the two sets describe the same constants.
    #[test]
    fn extended2_constants_are_consistent_with_rung1() {
        let pairs = [
            (super::pi_ext(), super::pi_ext2()),
            (super::e_ext(), super::e_ext2()),
            (super::ln2_ext(), super::ln2_ext2()),
            (super::ln10_ext(), super::ln10_ext2()),
            (super::inv_ln10_ext(), super::inv_ln10_ext2()),
            (super::inv_ln2_ext(), super::inv_ln2_ext2()),
            (super::pi_over_two_ext(), super::pi_over_two_ext2()),
            (super::pi_over_four_ext(), super::pi_over_four_ext2()),
            (
                super::tan_pi_over_eight_ext(),
                super::tan_pi_over_eight_ext2(),
            ),
        ];
        for (narrow, wide) in pairs {
            // |wide − widen(narrow)| relative to the value is below
            // 10^-54 (the 55-digit literal's own resolution).
            let widened = Extended2::from_extended(narrow);
            let d = wide.sub(widened);
            if d.is_zero() {
                continue;
            }
            let d_adj = d.exp + d.coef.decimal_digit_count() as i32 - 1;
            let w_adj = wide.exp + wide.coef.decimal_digit_count() as i32 - 1;
            assert!(
                d_adj <= w_adj - 54,
                "rung1/rung2 constant disagreement above 10^-54 relative"
            );
        }
    }
