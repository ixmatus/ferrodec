//! Extended-precision transcendental constants.
//!
//! Moved from `ferrodec/src/math/consts.rs` @ commit 82a7fe1
//! (P0a.2 c4). Only the format-agnostic half moves here: the nine
//! `*_EXT_STR` literals and their `*_ext()` [`Extended`] accessors,
//! plus the astro-float oracle that pins the literals. The
//! `Decimal128`-returning public `pi()` / `e()` / `ln2()` / `ln10()`
//! conveniences stay in the core crate (they are a Decimal128 API
//! surface, not a kernel internal).
//!
//! [`Extended`]: crate::extended::Extended

